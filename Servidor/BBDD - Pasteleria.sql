-- DROP DATABASE PASTELERIA;
CREATE DATABASE PASTELERIA;
USE PASTELERIA;

-- TABLA DE CLIENTE --
	CREATE TABLE CLIENTE (
		ID_CLIENTE INT NOT NULL AUTO_INCREMENT COMMENT 'ID DEL CLIENTE',
		NOMBRE VARCHAR(20) NOT NULL COMMENT 'NOMBRE DEL CLIENTE',
		APELLIDOS VARCHAR(45) NOT NULL COMMENT 'APELLIDOS DEL CLIENTE',
		CORREO VARCHAR(50) NOT NULL COMMENT 'CORREO ELECTRONICO',
		CONTRASEÑA VARCHAR(25) NOT NULL COMMENT 'CONTRASEÑA DEL CLIENTE',
		NUM_TLF INT NOT NULL COMMENT 'NUMERO DE TELEFONO',
		CONSTRAINT PRIMARY KEY (ID_CLIENTE)
	);

-- TABLA DE PRODUCTO --
	CREATE TABLE PRODUCTO (
		ID_PRODUCTO INT NOT NULL AUTO_INCREMENT COMMENT 'ID DEL PRODUCTO',
        NOMBRE VARCHAR(25) NOT NULL COMMENT 'NOMBRE DEL PRODUCTO',
        PRECIO DECIMAL(2) NOT NULL COMMENT 'PRECIO DEL PRODUCTO',
        DESCRIPCION VARCHAR(150) NULL COMMENT 'INFORMACION EXTRA SOBRE EL PRODUCTO',
		CONSTRAINT PRIMARY KEY (ID_PRODUCTO)
    );

-- TABLA DE PEDIDO -- 
	CREATE TABLE PEDIDO (
		ID_PEDIDO INT NOT NULL AUTO_INCREMENT COMMENT 'ID DEL PEDIDO',
		CLIENTE INT NOT NULL COMMENT 'ID DEL CLIENTE QUE HACE EL PEDIDO',
        PRODUCTO INT NOT NULL COMMENT 'ID DEL PRODUCTO QUE HA PEDIDO',
        FECHA_PEDIDO DATETIME NOT NULL COMMENT 'FECHA DE CUANDO SE REALIZA EL PEDIDO',
        CANTIDAD INT NOT NULL COMMENT 'CANTIDAD DEL PRODUCTO QUE PIDE',
        FECHA_ENTREGAA DATETIME NOT NULL COMMENT 'FECHA DE ENTREGA DEL PEDIDO',
        ESTADO ENUM ('EN PROCESO','ENTREGADO') NOT NULL COMMENT 'ESTADO DEL PEDIDO',
        TOTAL DECIMAL(10,2) NOT NULL COMMENT 'TOTAL A PAGAR POR EL CLIENTE',
        CONSTRAINT PRIMARY KEY (ID_PEDIDO),
        CONSTRAINT FOREIGN KEY (CLIENTE) REFERENCES CLIENTE(ID_CLIENTE),
        CONSTRAINT FOREIGN KEY (PRODUCTO) REFERENCES PRODUCTO(ID_PRODUCTO)
	);

-- TABLA INGREDIENTE --
	CREATE TABLE INGREDIENTE (
		ID_INGREDIENTE INT NOT NULL AUTO_INCREMENT COMMENT 'ID DEL INGREDIENTE',
        NOMBRE VARCHAR(20) NOT NULL COMMENT 'NOMBRE DEL INGREDIENTE',
        CANTIDAD INT NOT NULL COMMENT 'STOCK DE CADA INGREDIENTE',
        ALERGENOS VARCHAR(75) NULL COMMENT 'ALERGENOS DE CADA UNO DE LOS INGREDIENTES',
        CONSTRAINT PRIMARY KEY (ID_INGREDIENTE)
    );
    
-- TABLA INGREDIENTES DE LOS PRODUCTOS -- 
	CREATE TABLE INGREDIENTE_PRODUCTO (
		ID_IP INT NOT NULL AUTO_INCREMENT COMMENT 'ID DE LA TABLA',
        PRODUCTO INT NOT NULL COMMENT 'ID DEL PRODUCTO',
        INGREDIENTE INT NOT NULL COMMENT 'ID DEL INGREDIENTE',
        CONSTRAINT PRIMARY KEY (ID_IP),
        CONSTRAINT FOREIGN KEY (PRODUCTO) REFERENCES PRODUCTO(ID_PRODUCTO),
        CONSTRAINT FOREIGN KEY (INGREDIENTE) REFERENCES INGREDIENTE(ID_INGREDIENTE)
    );
    
-- EMPLEADOS Y JORNADAS -- 

-- EMPLEADO -- 
	CREATE TABLE EMPLEADO (
		USUARIO VARCHAR(20) NOT NULL COMMENT 'USUARIO DEL EMPLEADO', 
        CONTRASENA VARCHAR(15) NOT NULL COMMENT 'CONTRASEÑA DEL USUARIO',
        NOMBRE VARCHAR(20) NOT NULL COMMENT 'NOMBRE DEL USUARIO',
        APELLIDOS VARCHAR(45) NOT NULL COMMENT 'APELLIDOS DEL USUARIO',
        ADMINISTRADOR VARCHAR(1) NOT NULL COMMENT 'ES ADMIN?',
        CONSTRAINT PRIMARY KEY (USUARIO)
    );
    
-- JORNADA --
	CREATE TABLE JORNADA (
		ID_JORNADA INT NOT NULL AUTO_INCREMENT COMMENT 'ID DE LA JORNADA',
        EMPLEADO VARCHAR(20) NOT NULL COMMENT 'EMPLEADO QUE FICHA',
        FECHA DATE NOT NULL COMMENT 'DIA DE FICHAJE',
        HORA_INICIO TIME NOT NULL COMMENT 'HORA DE INICIO',
        HORA_SALIDA TIME NULL COMMENT 'HORA DE SALIDA',
        HORAS_DIA DECIMAL(2,1) NULL COMMENT 'HORAS DIARIAS',
        CONSTRAINT PRIMARY KEY (ID_JORNADA),
        CONSTRAINT FOREIGN KEY (EMPLEADO) REFERENCES EMPLEADO(USUARIO)
    );